# -*- coding: utf-8 -*-
"""gen_ui_font.py - build src/ui_font.c from a Windows CJK font.

The libnx console can only draw its built-in 8x8 ASCII font, so the whole UI is
rendered by ui_draw.c instead.  This script rasterises exactly the characters
the UI uses (ASCII + the Chinese strings below) into 1bpp glyphs and writes them
as a C table.  Re-run it whenever UI text changes - an unknown character is
drawn as '?'.

    python tools/gen_ui_font.py

Glyph cells: ASCII 8x16, everything else 16x16 (1bpp, MSB first, top-down).
"""
