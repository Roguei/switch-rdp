"""Host test harness for the interleaved-RLE decoder in src/rdp_update.c.

The decoder block is copied verbatim out of rdp_update.c (no hand copy, so the
test can never drift from the shipped code), wrapped with a tiny CLI that reads
"w h bpp hex" lines from stdin and prints an FNV-1a hash of the decoded RGB
buffer.  rle_sim.py prints the same hash, so the two implementations can be
diffed on a handful of hand-built order streams.
"""
import io
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "src", "rdp_update.c")
OUT = os.path.join(HERE, "_rle_test.c")
EXE = os.path.join(HERE, "_rle_test.exe")

with io.open(SRC, encoding="utf-8", newline="\n") as f:
    lines = f.read().split("\n")

start = end = None
for i, ln in enumerate(lines):
    if ln.startswith("#define RLE_BG_RUN"):
        start = i
    if ln.startswith("int rdp_update_bitmap("):
        end = i
        break
if start is None or end is None:
    raise SystemExit("could not locate the decoder block")

block = "\n".join(lines[start:end]).rstrip()

harness = r"""/* generated by tools/_mk_rle_test.py - do not edit */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

#define TILE_MAX_W 128
#define TILE_MAX_H 128

__BLOCK__

int main(void)
{
    char line[4096];
    while (fgets(line, sizeof(line), stdin))
    {
        char hex[2048];
        int w, h, bpp, n, i, k = 0;
        size_t len;
        uint8_t* raw;
        uint8_t rgb[128 * 128 * 3];
        uint32_t hash = 2166136261u;
        if (sscanf(line, "%d %d %d %2047s", &w, &h, &bpp, hex) != 4) continue;
        len = strlen(hex) / 2;
        raw = (uint8_t*)malloc(len ? len : 1);
        for (i = 0; i < (int)len; i++)
        {
            unsigned v;
            sscanf(hex + 2 * i, "%2x", &v);
            raw[i] = (uint8_t)v;
        }
        k = rle_decompress(raw, len, w, h, bpp, rgb);
        if (k == 0)
        {
            size_t j;
            for (j = 0; j < (size_t)w * (size_t)h * 3u; j++)
            {
                hash ^= rgb[j];
                hash *= 16777619u;
            }
        }
        printf("rc=%d hash=%08x\n", k, (unsigned)hash);
        free(raw);
    }
    return 0;
}
""".replace("__BLOCK__", block)

with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(harness)

# mingw gcc cannot open paths containing non-ASCII characters, so run it from
# the tools directory with plain relative names and its own DLL directory on PATH.
gcc = r"C:\devkitPro\msys2\mingw64\bin\gcc.exe"
env = dict(os.environ)
env["PATH"] = r"C:\devkitPro\msys2\mingw64\bin;" + env.get("PATH", "")
cmd = [gcc, "-O2", "-std=c99", "-Wall", "-o", os.path.basename(EXE), os.path.basename(OUT)]
print(" ".join(cmd))
rc = subprocess.call(cmd, cwd=HERE, env=env)
print("build rc=%d" % rc)
sys.exit(rc)
