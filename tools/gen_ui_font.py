def collect_chars():
    """Union of every non-ASCII character that appears in src/*.c|*.h, so the
    font always covers the strings the UI actually prints."""
    chars = set()
    for s in STRINGS:
        for ch in s:
            chars.add(ch)
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.abspath(os.path.join(here, "..", "src"))
    for name in os.listdir(src):
        if not name.endswith((".c", ".h")):
            continue
        if name.startswith("ui_font"):
            continue
        with io.open(os.path.join(src, name), encoding="utf-8", errors="ignore") as f:
            for ch in f.read():
                if ord(ch) > 0x7E:
                    chars.add(ch)
    for c in range(0x20, 0x7F):
        chars.add(chr(c))
    chars.add("?")
    return sorted(chars, key=ord)


def render(ch, font):
    wide = ord(ch) >= 0x80 or ch in "　"
    cw = WIDE_W if wide else NARROW_W
    img = Image.new("L", (cw, CELL_H), 0)
    d = ImageDraw.Draw(img)
    # msyh's ascent puts CJK nicely inside a 16px cell; ASCII needs a nudge
    d.text((0 if wide else 0, 0), ch, fill=255, font=font)
    return cw, img


def pack(img, cw):
    rows = []
    stride = (cw + 7) // 8
    px = img.load()
    for y in range(CELL_H):
        row = bytearray(stride)
        for x in range(cw):
            if px[x, y] >= 110:
                row[x >> 3] |= 0x80 >> (x & 7)
        rows.append(bytes(row))
    return b"".join(rows)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out_c = os.path.abspath(os.path.join(here, "..", "src", "ui_font.c"))
    out_h = os.path.abspath(os.path.join(here, "..", "src", "ui_font.h"))
    if not os.path.isfile(FONT_PATH):
        raise SystemExit("font missing: %s" % FONT_PATH)

    font = ImageFont.truetype(FONT_PATH, CELL_H, index=FONT_INDEX)
    chars = collect_chars()

    blob = bytearray()
    table = []
    for ch in chars:
        cw, img = render(ch, font)
        bits = pack(img, cw)
        table.append((ord(ch), cw, len(blob)))
        blob += bits

    with io.open(out_h, "w", encoding="utf-8", newline="\n") as f:
        f.write("""/* generated by tools/gen_ui_font.py - do not edit */
#ifndef UI_FONT_H
#define UI_FONT_H

#include <stdint.h>

typedef struct
{
    uint32_t cp;      /* code point */
    uint8_t  w;       /* cell width in pixels (8 or 16) */
    uint32_t off;     /* byte offset into ui_font_bits */
} ui_glyph;

#define UI_FONT_CELL_H 16
extern const uint8_t   ui_font_bits[];
extern const ui_glyph  ui_font_glyphs[];
extern const unsigned  ui_font_count;

/* Returns the glyph for a code point, or NULL. */
const ui_glyph* ui_font_lookup(uint32_t cp);

#endif
""")

    with io.open(out_c, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* generated by tools/gen_ui_font.py - do not edit */\n")
        f.write("#include \"ui_font.h\"\n\n")
        f.write("const uint8_t ui_font_bits[] = {\n")
        for i in range(0, len(blob), 16):
            f.write("    " + ",".join("0x%02X" % b for b in blob[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("const ui_glyph ui_font_glyphs[] = {\n")
        for cp, cw, off in table:
            f.write("    {0x%04X, %d, %d},\n" % (cp, cw, off))
        f.write("};\n\n")
        f.write("const unsigned ui_font_count = %d;\n\n" % len(table))
        f.write("""const ui_glyph* ui_font_lookup(uint32_t cp)
{
    unsigned lo = 0, hi = ui_font_count;
    while (lo < hi)
    {
        unsigned mid = (lo + hi) / 2;
        if (ui_font_glyphs[mid].cp < cp) lo = mid + 1;
        else hi = mid;
    }
    if (lo < ui_font_count && ui_font_glyphs[lo].cp == cp)
        return &ui_font_glyphs[lo];
    return 0;
}
""")

    print("glyphs: %d   blob: %d bytes" % (len(table), len(blob)))
    print("wrote %s\n      %s" % (out_c, out_h))


if __name__ == "__main__":
    main()
